def t(key: str, **kwargs: Any) -> str:
    """根据当前语言返回文案。

    @harbor.scope: public
    @harbor.l3_strictness: standard
    @harbor.idempotency: read-only

    Args:
      key (str): 文案键或模板。

    Returns:
      str: 本地化后的文案。
    """
    lang = get_lang()
    d = MESSAGES.get(lang) or MESSAGES["en"]
    tpl = d.get(key) or key
    if kwargs:
        try:
            return tpl.format(**kwargs)
        except Exception:
            return tpl
    return tpl
