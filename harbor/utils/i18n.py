import os
import locale
from pathlib import Path
from typing import Dict, Any, Optional
import yaml


def get_lang(config_path: Optional[Path] = None) -> str:
    """解析当前语言。

    功能:
      - 读取环境变量与配置文件以确定语言。
      - 回退到系统区域设置与英文。

    使用场景:
      - CLI 提示与用户可见错误的语言选择。

    依赖:
      - yaml.safe_load
      - locale.getdefaultlocale

    @harbor.scope: public
    @harbor.l3_strictness: standard
    @harbor.idempotency: read-only

    Args:
      config_path (Path | None): 指定配置文件路径，未提供时默认使用项目根的 `.harbor/config.yaml`。

    Returns:
      str: 语言代码，`zh` 或 `en`。
    """
    env = (os.environ.get("HARBOR_LANGUAGE") or os.environ.get("HARBOR_LANG") or "").strip().lower()
    if env in ("zh", "en"):
        return env
    canonical_cfg = Path.cwd() / ".harbor" / "config" / "harbor.yaml"
    legacy_cfg = Path.cwd() / ".harbor" / "config.yaml"
    cfg_file = config_path or (canonical_cfg if canonical_cfg.exists() else legacy_cfg)
    if cfg_file.exists():
        try:
            data = yaml.safe_load(cfg_file.read_text(encoding="utf-8")) or {}
        except Exception:
            data = {}
        lang = str(data.get("language", "") or "").strip().lower()
        if lang in ("zh", "en"):
            return lang
        if lang == "auto":
            return "en"
        elif lang:
            return "zh" if lang.startswith("zh") else "en"
    return "en"


